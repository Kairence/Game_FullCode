		public static void EquipOptionCreate(Item equip)
		{
			if (equip is not IEquipOption item) return;

			//신규 아이템 제작 코드
			/*
			아이템 접두, 접미 체크
			접두 : 아이템 기본 옵션(티어 등)
			접미 : 아이템 옵션 저장소
			
			접두 0 : 신규 아이템 체크 유무. 기본 값 10
			접미 0 : 옵션 갯수
			접두 1 : 아이템 세부 내구도(10000 => 내구도 1 하락)
			접미 1 : 랭크 레벨
			접두 2 : 숙련도
			접미 2 : 숙련도 최대치
			접두 3 : 재련 레벨	
			접미 3 : 1재련 값
			접두 4 : 2재련 값
			접미 4 : 3재련 값
			접두 5 : 4재련 값
			접미 5 : 5재련 값
			
			접두 9 : 랭크 옵션
			접미 9 : 랭크 값
			접두 10 : 강화 이름
			접미 10 : 강화 레벨
			
			접두 11 ~ 30 : 1 ~ 20 옵션 리스트.
			접미 11 ~ 30 : 1 ~ 20 옵션 저장값.
			
			접두 31 ~ 40 : 1 ~ 10 재련 리스트
			접미 31 ~ 40 : 1 ~ 10 재련 저장값
			
			접두 41 : 강화 이름
			접미 41 : 
			접두 42 ~ 45 : 1 ~ 4 재료 리스트
			접미 42 ~ 45 : 1 ~ 4 재료 저장값
			접두 50 : 세트 옵션 번호(1번 부터 시작)
			접미 50 : 세트 요구 수
			접두 51 ~ 60 : 세트 옵션 리스트
			접미 51 ~ 60 : 세트 옵션 저장값
			
			접두 61 ~ 70 : 기본 옵션 리스트.
			접미 61 ~ 70 : 기본 옵션 저장값.
			
			스킬 붙을 시 지정 칸 0 ~ 9
			0 ~ 4 : 랜덤 및 고정 옵션
			5 ~ 7 : 기본 옵션
			8 ~ 9 : 세트 옵션
			*/					

			// [중요] TotalAttrs.Clear() 및 AddValue()는 더 이상 사용하지 않습니다.
			// 합산 연산은 PlayerMobile.UpdateEquipOptions()에서 Prefix/Suffix 배열을 직접 읽어 처리합니다.

			#region 강화 재료 옵션 (최종 최적화)

			// 아이템의 재질(Resource)에 따른 옵션 인덱스를 Prefix 10번에 저장
			int resIndex = Misc.Util.UseResourceNumber((int)item.Resource);

			item.PrefixOption[10] = (resIndex >= 0) ? resIndex : 0;
			// SuffixOption[10]은 강화 성공 시 레벨을 올리는 용도로 사용됨 (초기값 유지)

			#endregion

			// 아이템 툴팁(OPL) 등 정보 갱신 요청
			equip.InvalidateProperties();

			// 만약 플레이어가 이 아이템을 입고 있는 상태에서 호출되었다면 스탯 즉시 갱신
			if (equip.Parent is PlayerMobile pm)
			{
				pm.UpdateEquipOptions();
			}
		}
