		// 1080578부터 시작
		public static int NewEquipNumber(Item equip)
		{
			if (equip is not IEquipOption) return -1;

			// C# 12 패턴 매칭으로 타입별 즉시 분류
			return equip switch
			{
				BaseWeapon weapon => WeaponList(weapon),
				BaseArmor armor => ArmorList(armor),
				BaseClothing cloth when cloth.Layer is Layer.Neck or Layer.Gloves or Layer.Arms or Layer.Helm or Layer.Pants or Layer.InnerTorso => (int)LootGroup.Cloth, // 11
				BaseJewel jewel => JewelList(jewel),
				Spellbook => (int)LootGroup.Spellbook, // 9
				BaseInstrument => 27,
				_ => -1
			};
		}

		public static int WeaponList(BaseWeapon weapon)
		{
			// 원거리 무기 판정
			if (weapon is BaseRanged ranged)
			{
				return ranged.AmmoType == typeof(Bolt) ? (int)LootGroup.Crossbow : (int)LootGroup.Bow; // 8 or 7
			}

			// 근접 무기 스킬별 판정
			return weapon.Skill switch
			{
				SkillName.Swords => weapon is BaseAxe ? (int)LootGroup.Axe : (weapon.Layer == Layer.TwoHanded ? (int)LootGroup.Sword2H : (int)LootGroup.Sword1H), // 2, 1, 0
				SkillName.Macing => weapon.Layer == Layer.TwoHanded ? (int)LootGroup.Mace2H : (int)LootGroup.Mace1H, // 4, 3
				SkillName.Fencing => weapon.Layer == Layer.TwoHanded ? (int)LootGroup.Fencing2H : (int)LootGroup.Fencing1H, // 6, 5
				_ => -1
			};
		}

		public static int ArmorList(BaseArmor armor)
		{
			/*
			아머타입 10 : 방패 //탱커
			아머타입 11 : 천옷 //법사, 힐러
			아머타입 12 : 가죽 //도적
			아머타입 13 : 스텃 //아쳐
			아머타입 14 : 뼈 //서포터
			아머타입 15 : 링, 투구, 스톤 //근접 딜러
			아머타입 16 : 체인, 스톤 //근접 딜러
			아머타입 17 : 플레이트 //탱커
			아머타입 18 : 나무 //서포터
			*/
			if (armor is BaseShield)
				return (int)LootGroup.Shield; // 10

			int check = 1 + (int)armor.MaterialType;

			// 기존 if-else 로직을 C# 12의 간결한 and/or 패턴으로 압축
			if (check is >= 5 and <= 7) 
				check = 2;
			else if (armor is Helmet or Bascinet or CloseHelm or NorseHelm || check == 8) 
				check = 5;
			else if (check is 9 or 13) 
				check = 6;
			else if (check == 10) 
				check = 7;
			else if (check == 12) 
				check = 8;

			return check + 10;
		}

		public static int JewelList(BaseJewel jewel)
		{
			/*
			악세타입 19 : 팔찌 
			아머타입 20 : 반지 
			아머타입 21 : 목걸이 
			아머타입 22 : 귀걸이 
			*/
			int check = jewel.Layer switch
			{
				Layer.Ring => (int)LootGroup.WarRing, // 20
				Layer.Neck => (int)LootGroup.WarNeck, // 21
				Layer.Earrings => (int)LootGroup.WarEar, // 22
				_ => (int)LootGroup.WarBrace // 19 (팔찌)
			};

			// 실버 악세사리(마법형)는 +4 처리 (23~26)
			if (jewel is SilverEarrings or SilverRing or SilverBracelet or SilverNecklace)
			{
				check += 4;
			}

			return check;
		}
		
